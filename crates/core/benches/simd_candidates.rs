//! Scalar-vs-SIMD measurements for the log-parsing hot path.
//!
//! # What this measures and why
//!
//! A callgrind profile of the end-to-end parse attributes ~28% of instructions
//! to `regex_automata`'s bounded backtracker — the engine the `regex` crate
//! falls back to for *capture extraction* on short haystacks — and ~14% to
//! malloc/free. The patterns responsible all describe fixed byte shapes
//! (a timestamp, a `(cost=..)` tuple, a leading-whitespace run, a set of
//! literal node-type names), which is exactly the work byte-parallel compares
//! do well.
//!
//! Each group below measures **three tiers** on the same input:
//!
//! * `current` — what the parser does today (regex, or `char`-by-`char`).
//! * `scalar`  — the same job as a plain byte loop, no regex, no allocation.
//! * `simd`    — the byte loop vectorised (SSE2/AVX2, runtime-detected).
//!
//! Reporting all three is the point. Replacing a regex with a byte scanner
//! bundles two separate wins — *not running a regex engine* and *comparing 16
//! or 32 bytes at once* — and only the second is attributable to SIMD. The
//! `scalar` tier is what separates them; without it a "20x SIMD speedup" claim
//! would mostly be measuring the regex removal.
//!
//! # Input realism
//!
//! The corpus is generated by the same auto_explain log generator used by
//! `benches/log_parsing.rs` and `benches/grouping.rs` (itself modeled on the
//! fixtures in the `log_parser` unit tests): ~89% tab-indented continuation
//! lines, ~2.3 KB per plan, long `Filter:` lines, and interleaved unrelated
//! server log lines. Crucially, each scanner is measured over the line mix it
//! would really see — the timestamp split over *every* line including the
//! continuations it must reject, not just over timestamps it can match.
//!
//! Every fast path is checked against its current implementation over the
//! whole corpus before timing starts, so the numbers cannot come from a
//! scanner that silently does less work.

