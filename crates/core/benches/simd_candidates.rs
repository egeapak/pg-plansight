fn format_ts(ms: u64) -> String {
    let day = 12 + ms / 86_400_000;
    let rem = ms % 86_400_000;
    format!(
        "2025-06-{:02} {:02}:{:02}:{:02}.{:03}",
        day,
        rem / 3_600_000,
        (rem / 60_000) % 60,
        (rem / 1000) % 60,
        rem % 1000
    )
}

fn push_plan(out: &mut String, i: usize, shape: usize, ts_ms: u64, table: &str) {
    let pid = 3_416_000 + i % 800;
    let duration = 10.0 + ((i % 997) as f64) * 1.37;
    writeln!(
        out,
        "{} UTC [{pid}] LOG:  duration: {duration:.3} ms  plan:",
        format_ts(ts_ms)
    )
    .unwrap();
    writeln!(
        out,
        "\tQuery Text: SELECT t.\"Id\", t.\"Status\", t.\"CreatedAt\", t.\"Payload\", t.\"OwnerId\""
    )
    .unwrap();
    writeln!(out, "\tFROM \"public\".\"{table}\" AS t").unwrap();
    writeln!(
        out,
        "\tWHERE t.\"Status\" = $1 AND t.\"CreatedAt\" >= $2 AND t.\"OwnerId\" IN ($3, $4)"
    )
    .unwrap();
    if shape.is_multiple_of(2) {
        writeln!(out, "\tORDER BY t.\"CreatedAt\" DESC").unwrap();
    }
    if shape % 4 < 3 {
        writeln!(out, "\tLIMIT $5").unwrap();
    }
    writeln!(out, "\tLimit  (cost=0.43..599.04 rows=1000 width=56)").unwrap();
    writeln!(
        out,
        "\t  Output: \"Id\", \"Status\", \"CreatedAt\", \"Payload\", \"OwnerId\""
    )
    .unwrap();
    writeln!(
        out,
        "\t  ->  Index Scan Backward using \"IX_{table}_CreatedAt\" on \"public\".\"{table}\" t  (cost=0.43..95610.13 rows=159718 width=56)"
    )
    .unwrap();
    writeln!(
        out,
        "\t        Output: \"Id\", \"Status\", \"CreatedAt\", \"Payload\", \"OwnerId\""
    )
    .unwrap();
    writeln!(out, "\t        Index Cond: (t.\"CreatedAt\" IS NOT NULL)").unwrap();
    writeln!(
        out,
        "\t        Filter: ((NOT t.\"Deleted\") AND (((t.\"Level\" > '66'::double precision) AND (t.\"Level\" <= '99'::double precision) AND (t.\"CreatedAt\" <= '2025-06-11 23:00:15.671506+00'::timestamp with time zone)) OR ((t.\"Level\" <= '66'::double precision) AND (t.\"CreatedAt\" <= '2025-06-11 23:30:15.671506+00'::timestamp with time zone))) AND (t.\"Status\" = ANY ('{{1,2,3,4}}'::integer[])))"
    )
    .unwrap();
    for j in 0..(4 + i % 9) {
        writeln!(
            out,
            "\t        ->  Bitmap Heap Scan on \"public\".\"{table}_c{j}\" c{j}  (cost=12.15..870.{j:02} rows={} width=24)",
            100 + j * 7
        )
        .unwrap();
    }
    writeln!(
        out,
        "{} UTC [{}] LOG:  checkpoint complete: wrote {} buffers (0.4%); sync files={}",
        format_ts(ts_ms + 3),
        pid + 1,
        100 + i % 500,
        i % 32
    )
    .unwrap();
}

fn realistic_log(num_plans: usize) -> String {
    let mut out = String::with_capacity(num_plans * 2400);
    for i in 0..num_plans {
        let shape = i % 20;
        let table = format!("tbl_{shape}");
        push_plan(&mut out, i, shape, (i as u64) * 47, &table);
    }
    out
}

/// The line slices each scanner is measured over.
struct Corpus {
    /// Every line, in file order — the mix the read loop really sees.
    all: Vec<String>,
    /// Only the timestamped lines (~11% of `all`).
    timestamped: Vec<String>,
    /// Continuation lines with leading indentation stripped of the leading
    /// tab, as `PlanLine::new` receives them.
    plan_lines: Vec<String>,
    /// Only lines carrying a `(cost=..)` tuple — the node lines.
    node_lines: Vec<String>,
}

fn corpus(num_plans: usize) -> Corpus {
    let content = realistic_log(num_plans);
    let all: Vec<String> = content.lines().map(str::to_string).collect();
    let timestamped: Vec<String> = all
        .iter()
        .filter(|l| l.as_bytes().first().is_some_and(u8::is_ascii_digit))
        .cloned()
        .collect();
    let plan_lines: Vec<String> = all
        .iter()
        .filter(|l| l.starts_with('\t'))
        .map(|l| l.trim_start_matches('\t').to_string())
        .collect();
    let node_lines: Vec<String> = plan_lines
        .iter()
        .filter(|l| l.contains("(cost="))
        .cloned()
        .collect();
    Corpus {
        all,
        timestamped,
        plan_lines,
        node_lines,
    }
}

fn total_bytes(lines: &[String]) -> u64 {
    lines.iter().map(|l| l.len() as u64).sum()
}

// ---------------------------------------------------------------------------
// 1. Timestamp split — `split_log_line` / LOG_LINE_PATTERN group 1.
// ---------------------------------------------------------------------------

/// Byte-scanner drop-in for [`split_log_line`], deferring to the regex only
/// when the fast path reports [`Verdict::Unsure`]. This is the shape a real
/// integration would take, so it is what gets measured — including the
/// fallback branch.
#[inline]
fn split_scanned<'a>(
    line: &'a str,
    fallback: &Regex,
    scan: fn(&[u8]) -> Verdict,
) -> Option<(&'a str, &'a str)> {
    match scan(line.as_bytes()) {
        Verdict::Match(n) => Some((&line[..n], &line[n..])),
        Verdict::NoMatch => None,
        Verdict::Unsure => {
            let caps = fallback.captures(line)?;
            Some((caps.get(1)?.as_str(), caps.get(2)?.as_str()))
        }
    }
}

/// The pre-integration `split_log_line`, kept verbatim here.
///
/// The library version now answers from the byte scanner, so calling it would
/// make this group measure the scanner against itself. Holding the old
/// implementation locally keeps `current_regex` meaningful as the baseline it
/// is labelled as.
#[inline]
fn split_legacy_regex<'a>(line: &'a str, fallback: &Regex) -> Option<(&'a str, &'a str)> {
    let first = *line.as_bytes().first()?;
    if first.is_ascii() && !first.is_ascii_digit() {
        return None;
    }
    let caps = fallback.captures(line)?;
    Some((caps.get(1)?.as_str(), caps.get(2)?.as_str()))
}

/// The pre-integration `get_indent_level`, kept for the same reason.
#[inline]
fn indent_legacy_chars(line: &str) -> usize {
    line.chars().take_while(|c| c.is_whitespace()).count()
}

fn bench_timestamp_split(c: &mut Criterion) {
    let corpus = corpus(400);
    // The exact regex the parser uses, rather than a copy of the pattern.
    let re = RegexPatterns::default().log_line_regex;

    // Equivalence gate: both scanners must agree with the production splitter
    // on every line of the corpus before any timing is reported.
    for line in &corpus.all {
        let want = split_legacy_regex(line, &re);
        // The shipped `split_log_line` is now the integrated scanner; assert it
        // still agrees with the regex it replaced.
        assert_eq!(
            split_log_line(line, &re),
            want,
            "shipped split disagrees on {line:?}"
        );
        assert_eq!(
            split_scanned(line, &re, timestamp_prefix_len_scalar),
            want,
            "scalar timestamp split disagrees on {line:?}"
        );
        assert_eq!(
            split_scanned(line, &re, timestamp_prefix_len_simd),
            want,
            "simd timestamp split disagrees on {line:?}"
        );
    }

    // Two views: the realistic mix (where the existing tab fast-reject already
    // skips ~89% of lines) and timestamped lines only (where the regex
    // actually runs). The first is the honest end-to-end figure; the second
    // isolates the win on the lines that pay for it.
    for (name, lines) in [
        ("realistic_mix", &corpus.all),
        ("timestamped_only", &corpus.timestamped),
    ] {
        let mut group = c.benchmark_group(format!("timestamp_split/{name}"));
        group.throughput(Throughput::Elements(lines.len() as u64));

        group.bench_function("current_regex", |b| {
            b.iter(|| {
                for line in lines.iter() {
                    black_box(split_legacy_regex(black_box(line), &re));
                }
            });
        });
        group.bench_function("scalar", |b| {
            b.iter(|| {
                for line in lines.iter() {
                    black_box(split_scanned(
                        black_box(line),
                        &re,
                        timestamp_prefix_len_scalar,
                    ));
                }
            });
        });
        // Measures the shipped `split_log_line`, i.e. the integrated path.
        group.bench_function("simd", |b| {
            b.iter(|| {
                for line in lines.iter() {
                    black_box(split_log_line(black_box(line), &re));
                }
            });
        });
        group.finish();
    }
}

